1. 只输出 JSON 本身，不要 markdown 代码块，不要任何解释文字
2. intents 与 actions 各 2~3 项；每项 p 是 0~1 的小数；各项之和等于 1
3. 概率要真实反映判断，禁止一律写 0.5
