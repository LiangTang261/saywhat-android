     * 写进 `her_message` 字段 —— 因为我们读不到，卡片上要引用哪句全靠它。
     */
    const val SYSTEM_VISION: String = """你是「潜台词分析引擎」。用户给你一张**微信聊天界面的截图**（只截了聊天区域）。

