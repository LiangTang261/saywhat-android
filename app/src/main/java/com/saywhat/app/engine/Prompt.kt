   - 如果对方最后发的不是文字（比如表情包、语音、图片），就描述它，写成 `[表情包]`、`[语音]` 这类形式
   - 如果实在看不清，`her_message` 写 `""`
2. **再分析**这句话的潜台词，规则与下面完全一致

━━ 情境 scene（五选一）━━
