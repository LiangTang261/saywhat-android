package com.saywhat.app.data

/**
 * 悬浮球上显示的字符。
 *
 * ═══ 默认是 👀（御主 2026-09-23 拍板）═══
 * 沿革：最早默认 `J`（呼应参考图里那个叫 Jev 的模型）→ 改成 `她`
 * （新用户看不懂孤零零一个字母）→ 现在定为 **👀**。
 *
 * 为什么选 👀：它是唯一「一眼就知道这个球在干什么」的字形 ——
 * 「看穿 / 读懂」正是本 App 的动作，不需要任何解释成本。
 * 御主同时要求**删掉 `J` 这个选项**：一个需要看注释才懂的历史缩写，
 * 留在下拉里只会让人问「J 是什么」。
 *
 * ⚠️ 兼容性：老用户机器上存的是旧 id（可能是 `J`）。
 * [glyphOf] 认不出来就退回**第一个**，所以 `J` 会自动落到 `👀` ——
 * 不需要写迁移代码，也不会出现空白球。
 */
object BallStyles {

    /** 存进 Settings 的 id → 实际显示的字符。**第一个即默认值** */
    val ALL: List<Pair<String, String>> = listOf(
        "eye" to "👀",
        "她" to "她",
        "潜" to "潜",
        "talk" to "💬"
    )

    /** 设置页下拉里显示的文字 */
    val LABELS: List<String> = listOf(
        "👀 —— 看穿（默认）",
        "她 —— 分析对象是\"她\"",
        "潜 —— 潜台词",
        "💬 —— 聊天气泡"
    )

    /**
     * 把 id 转成要显示的字符。
     * 认不出来就退回第一个 —— 用户改过配置后又回滚版本、或选项被删掉时，
     * 都不该出现一个空白球。
     */
    fun glyphOf(id: String?): String =
        ALL.firstOrNull { it.first == id }?.second ?: ALL.first().second
}
